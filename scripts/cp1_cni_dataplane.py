"""Lossless compatibility coverage for the observed CP1 nft/xtables backend.

No mutations, permission grants, or generic Calico/kube-proxy exclusions.
The native representation and every xtables parameter and kernel ipset entry
are retained together. Equality means paired observations agreed, not an
atomic snapshot, packet-flow success, or a qualified Pod replacement.
"""
import copy
import json
import re
import shlex

from cp1_cni_membership import need, fingerprint

NAME = re.compile(r'[A-Za-z0-9_.:+-]{1,128}')
TABLES = {'filter', 'nat', 'mangle', 'raw', 'security'}
BUILTINS = {'filter': {'INPUT', 'FORWARD', 'OUTPUT'},
            'nat': {'PREROUTING', 'INPUT', 'OUTPUT', 'POSTROUTING'},
            'mangle': {'PREROUTING', 'INPUT', 'FORWARD', 'OUTPUT', 'POSTROUTING'},
            'raw': {'PREROUTING', 'OUTPUT'}, 'security': {'INPUT', 'FORWARD', 'OUTPUT'}}
MATCHES = {'comment', 'conntrack', 'set', 'addrtype', 'multiport', 'tcp', 'udp', 'statistic', 'rpfilter'}
TARGETS = {'MARK', 'DNAT', 'MASQUERADE', 'CT', 'REJECT'}
CAPTURE_KEYS = set('boot kernel packages containerd_version native_json native_text iptables_version iptables_save '
    'ip6tables_save ipsets links routes runtime_zones runtime_policies permanent_zones permanent_policies '
    'pods namespaces serviceaccounts services endpointslices networkpolicies calico_networkpolicies '
    'calico_globalnetworkpolicies calico_hostendpoints calico_networksets calico_globalnetworksets calico_felix '
    'calico_ippools calico_blocks calico_affinities calico_daemonset calico_config kube_proxy_config '
    'kube_proxy_daemonset'.split())


def parse_json(raw):
    def pairs(items):
        result = {}
        for key, value in items:
            need(key not in result, 'duplicate dataplane JSON key')
            result[key] = value
        return result
    def invalid(value):
        raise ValueError('non-finite dataplane number: ' + value)
    return json.loads(raw, object_pairs_hook=pairs, parse_constant=invalid)


def output(record):
    need(type(record.get('rc')) is int and record['rc'] == 0 and
         record.get('stdout_truncated', False) is False and
         record.get('stderr_truncated', False) is False and
         isinstance(record.get('stderr'), str) and not record['stderr'].strip() and
         isinstance(record.get('stdout'), str), 'incomplete compatibility query')
    return record['stdout']


def lines(raw):
    need(isinstance(raw, str) and len(raw.encode()) <= 2 * 1024 * 1024 and '\x00' not in raw,
         'dataplane text size/encoding invalid')
    return raw.splitlines()


def iptables(raw):
    """Keep all rule tokens and order; remove only line/chain counters.

    Unknown text is an error. In particular comments inside --comment, or
    literal strings that look like counters, are not rewritten.
    """
    tables, current = {}, None
    for line in lines(raw):
        if not line: continue
        if line.startswith('#'):
            need(re.fullmatch(r'# (?:Generated by ip6?tables-save v1\.8\.11 \(nf_tables\) on .+|Completed on .+)', line),
                 'unknown xtables header/backend')
            continue
        if line.startswith('*'):
            name = line[1:]
            need(current is None and name in TABLES and name not in tables, 'duplicate/unknown xtables table')
            current = tables[name] = {'chains': {}, 'rules': []}
        elif line == 'COMMIT':
            need(current is not None, 'unexpected xtables COMMIT')
            current = None
        elif line.startswith(':'):
            match = re.fullmatch(r':([^ ]+) (ACCEPT|DROP|-) \[([0-9]+):([0-9]+)\]', line)
            need(current is not None and match is not None, 'invalid xtables chain')
            name, policy = match.group(1, 2)
            need(NAME.fullmatch(name) and name not in current['chains'], 'duplicate/invalid xtables chain')
            current['chains'][name] = policy
        else:
            match = re.fullmatch(r'\[[0-9]+:[0-9]+\] (-A .+)', line)
            need(current is not None and match is not None, 'unsupported xtables command/counters')
            tokens = shlex.split(match.group(1), comments=False, posix=True)
            need(len(tokens) >= 2 and tokens[:1] == ['-A'] and tokens[1] in current['chains'],
                 'xtables rule chain absent')
            current['rules'].append(tokens)
    need(current is None and tables, 'incomplete/empty xtables save')
    return tables


def ipsets(raw):
    result = {}
    for line in lines(raw):
        if not line: continue
        tokens = shlex.split(line, comments=False, posix=True)
        need(len(tokens) >= 3 and NAME.fullmatch(tokens[1]), 'invalid kernel ipset record')
        action, name = tokens[:2]
        if action == 'create':
            need(name not in result and tokens[2] in ('hash:ip', 'hash:net'),
                 'duplicate/unsupported kernel ipset')
            need(len(tokens[3:]) % 2 == 0, 'unsupported kernel ipset flags')
            options = dict(zip(tokens[3::2], tokens[4::2]))
            need(len(options) * 2 == len(tokens[3:]) and
                 set(options) <= {'family', 'hashsize', 'maxelem', 'bucketsize', 'initval'} and
                 options.get('family') in ('inet', 'inet6'), 'dynamic/unknown kernel ipset options')
            result[name] = {'definition': tokens[2:], 'entries': []}
        else:
            need(action == 'add' and name in result and len(tokens) == 3,
                 'unknown ipset operation/element options')
            need(tokens[2] not in result[name]['entries'], 'duplicate kernel ipset entry')
            result[name]['entries'].append(tokens[2])
    for value in result.values(): value['entries'].sort()
    return result


def native(raw):
    result = copy.deepcopy(raw)
    need(isinstance(result, dict) and set(result) == {'nftables'} and
         isinstance(result['nftables'], list) and result['nftables'], 'native ruleset absent')
    for item in result['nftables']:
        need(isinstance(item, dict) and len(item) == 1, 'ambiguous native object')
        kind, value = next(iter(item.items()))
        need(isinstance(value, dict), 'invalid native body')
        counters = [value] if kind == 'counter' else []
        if kind == 'rule':
            need(isinstance(value.get('expr'), list), 'native rule expressions absent')
            for expr in value['expr']:
                need(isinstance(expr, dict) and len(expr) == 1, 'ambiguous native expression')
                if 'counter' in expr and isinstance(expr['counter'], dict):
                    need(set(expr['counter']) == {'packets', 'bytes'}, 'unknown anonymous counter fields')
                    counters.append(expr['counter'])
        for counter in counters:
            need(all(type(counter.get(k)) is int and counter[k] >= 0 for k in ('packets', 'bytes')),
                 'invalid native counter')
            counter.update(packets=0, bytes=0)
    return result


def option(tokens, name):
    """All occurrences, not dict(): repeated --comment/-m must survive."""
    found = []
    for i, token in enumerate(tokens):
        if token == name:
            need(i + 1 < len(tokens), 'missing xtables option value')
            found.append(tokens[i + 1])
    return found


def covered(raw_native, raw4, raw6, rawsets):
    """Require ordered, whole-chain correspondence before covering opaque xt.

    Empty ACCEPT built-ins synthesized by iptables-save may be absent from
    nft JSON. Every nonempty chain/rule and every xt extension must be covered.
    Unknown native objects remain in the fixed digest; they are never deleted.
    """
    view = native(raw_native)
    saves = {'ip': iptables(raw4), 'ip6': iptables(raw6)}
    sets = ipsets(rawsets)
    chains, rules, tables = {}, {}, {}
    for item in view['nftables']:
        kind, value = next(iter(item.items()))
        if kind == 'table':
            key = value.get('family'), value.get('name')
            need(key not in tables, 'duplicate native table'); tables[key] = value
        if kind == 'chain':
            key = value.get('family'), value.get('table'), value.get('name')
            need(key not in chains, 'duplicate native chain'); chains[key] = value
        if kind == 'rule':
            key = value.get('family'), value.get('table'), value.get('chain')
            rules.setdefault(key, []).append(value)
    for key, group in rules.items():
        need(key in chains, 'native rule without chain')
        if any('xt' in e for r in group for e in r['expr']):
            need(key[0] in saves and key[1] in saves[key[0]] and
                 key[2] in saves[key[0]][key[1]]['chains'], 'opaque xt outside saved tables')
    xt_count = 0
    for family, save in saves.items():
        for table, data in save.items():
            need((family, table) in tables, 'saved table absent from native')
            for name, policy in data['chains'].items():
                key = family, table, name
                saved_rules = [t for t in data['rules'] if t[1] == name]
                compiled = chains.get(key)
                if compiled is None:
                    need(not saved_rules and policy == 'ACCEPT' and name in BUILTINS[table],
                         'saved chain absent from native')
                    continue
                need(compiled.get('policy', '-').upper() == policy and
                     len(saved_rules) == len(rules.get(key, [])), 'native/saved chain policy or rule count differs')
                for tokens, rule in zip(saved_rules, rules.get(key, [])):
                    modules = option(tokens, '-m')
                    # mark and some TCP/UDP predicates are translated to native
                    # expressions. Opaque modules must retain order and count.
                    required = [m for m in modules if m not in {'mark', 'tcp', 'udp'}]
                    seen, targets = [], []
                    for expr in rule['expr']:
                        if 'xt' not in expr: continue
                        xt = expr['xt']; xt_count += 1
                        need(set(xt) == {'type', 'name'}, 'unknown opaque xt payload form')
                        if xt['type'] == 'match':
                            need(xt['name'] in MATCHES, 'unsupported opaque xt match')
                            seen.append(xt['name'])
                        else:
                            need(xt['type'] == 'target' and xt['name'] in TARGETS,
                                 'unsupported opaque xt target')
                            targets.append(xt['name'])
                    need([m for m in seen if m not in {'tcp', 'udp'}] == required and
                         all(seen.count(m) <= modules.count(m) for m in ('tcp', 'udp')),
                         'native/saved extension sequence differs')
                    jumps = option(tokens, '-j'); gotos = option(tokens, '-g')
                    need(len(jumps) + len(gotos) <= 1, 'multiple xtables verdicts')
                    expect_target = ['CT' if t == 'NOTRACK' else t for t in jumps if t in TARGETS | {'NOTRACK'}]
                    need(targets == expect_target, 'native/saved opaque target differs')
                    expected_edges = ([{'jump': {'target': t}} for t in jumps if t in data['chains']] +
                                      [{'goto': {'target': t}} for t in gotos])
                    actual_edges = [e for e in rule['expr'] if set(e) in ({'jump'}, {'goto'})]
                    need(actual_edges == expected_edges, 'native/saved chain edge differs')
                    verdicts = {'ACCEPT': 'accept', 'DROP': 'drop', 'RETURN': 'return'}
                    need(all(t in data['chains'] or t in TARGETS | set(verdicts) | {'NOTRACK'} for t in jumps),
                         'unsupported saved target')
                    expected_verdicts = [{verdicts[t]: None} for t in jumps if t in verdicts]
                    actual_verdicts = [e for e in rule['expr'] if set(e) & {'accept', 'drop', 'return'}]
                    need(actual_verdicts == expected_verdicts, 'native/saved terminal verdict differs')
                    for name in option(tokens, '--match-set'):
                        need(name in sets and ('inet' if family == 'ip' else 'inet6') in sets[name]['definition'],
                             'kernel ipset dependency absent/family differs')
            need({key[2] for key in chains if key[:2] == (family, table)} <= set(data['chains']),
                 'native chain omitted by save')
    return {'native': view, 'xtables': saves, 'kernel_ipsets': sets, 'opaque_expressions': xt_count}


def paired(queries, *, native_key='native_json'):
    views = []
    for suffix in ('', '_after'):
        views.append(covered(parse_json(output(queries[native_key + suffix])),
                             output(queries['iptables_save' + suffix]),
                             output(queries['ip6tables_save' + suffix]), output(queries['ipsets' + suffix])))
    need(views[0] == views[1], 'dataplane changed during paired observation')
    return views[0]


def assess_capture(record):
    """Offline assessment only: never a substitute for a fresh root observer."""
    need(record.get('schema') == 'fds.cp1-cni-dataplane-capture.v1' and record.get('complete') is True and
         record.get('errors') == [] and record.get('authorizes_apply') is False, 'complete read-only capture required')
    need(record.get('host') == 'k8s-control01' and record.get('mode') == 'READ_ONLY' and
         record.get('paired_observation') is True and record.get('atomic_snapshot') is False and
         type(record.get('elapsed_seconds')) in (int, float) and 0 <= record['elapsed_seconds'] <= 240,
         'capture identity/timing differs')
    q = record['queries']
    need(set(q) == {key + s for key in CAPTURE_KEYS for s in ('', '_after')} | {'boot_final'},
         'capture query inventory differs')
    need(output(q['boot']).strip() == output(q['boot_after']).strip() == output(q['boot_final']).strip(),
         'capture boot changed')
    need(output(q['iptables_version']).strip() == output(q['iptables_version_after']).strip() ==
         'iptables v1.8.11 (nf_tables)', 'unsupported xtables backend/version')
    view = paired(q)
    warnings = {}
    # Human-readable text is retained as diagnostic evidence, not used instead
    # of the validated JSON + both save streams + kernel sets.
    for key, value in q.items():
        if key in ('native_text', 'native_text_after'):
            need(type(value.get('rc')) is int and value['rc'] == 0 and
                 value.get('stdout_truncated') is False and value.get('stderr_truncated') is False,
                 'incomplete native diagnostic text')
            if value.get('stderr'): warnings[key] = value['stderr'].splitlines()
        else: output(value)
    other_differences = []
    for key in sorted(CAPTURE_KEYS - {'native_json', 'native_text', 'iptables_save', 'ip6tables_save', 'ipsets'}):
        if output(q[key]) != output(q[key + '_after']): other_differences.append(key)
    need(not other_differences, 'paired context changed: ' + ','.join(other_differences))
    return {'schema': 'fds.cp1-cni-dataplane-assessment.v1', 'status': 'PAIRED_DATAPLANE_COVERED',
            'fixed_dataplane_sha256': fingerprint(view), 'opaque_expressions': view['opaque_expressions'],
            'kernel_ipsets': len(view['kernel_ipsets']), 'query_count': len(q), 'warnings': warnings,
            'paired_context_changed': other_differences,
            'atomic_snapshot': False, 'pod_replacement_qualified': False,
            'authorizes_apply': False, 'authorizes_cp1_acceptance': False, 'authorizes_cp2_change': False}
